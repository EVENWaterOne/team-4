#!/usr/bin/env node
// Builds the public web copy of the game into clementi-demo/web/out (static files only).
// It takes clementi-demo/dist as is, keeps only what index.html loads (plus licence notes),
// turns on server-side AI on any http(s) host, and rewords the launcher-only hints in the AI settings panel. The dialogue proxy is api/*.mjs next to this file.
// It also refreshes api/_lib/prompts.mjs, the list of system prompts the proxy accepts.
// Usage: node clementi-demo/web/build.cjs   (the host runs the same command)
const fs = require('fs');
const path = require('path');

const here = __dirname;
const dist = path.join(here, '..', 'dist');
const out = path.join(here, 'out');

const read = file => fs.readFileSync(path.join(dist, file), 'utf8');
const fail = message => { console.error('build failed: ' + message); process.exit(1); };

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

// 1. The files index.html loads, and the licence notes that travel with them.
const html = read('index.html');
const refs = [...html.matchAll(/\b(?:href|src)="([^"#?]+)"/g)].map(m => m[1]).filter(ref => !/^[a-z]+:|^\/\//i.test(ref));
const files = ['index.html', ...new Set(refs), 'three-LICENSE.txt', 'vendor/downstairs-ai/NOTICE.md', 'vendor/downstairs-ai/SOURCE.md'];
for (const file of files) {
  const from = path.join(dist, file);
  if (!fs.existsSync(from)) fail('index.html needs ' + file + ', which is missing from dist');
  fs.mkdirSync(path.dirname(path.join(out, file)), { recursive: true });
  fs.copyFileSync(from, path.join(out, file));
}

// 2. AI is on only for 127.0.0.1/localhost in main. On the web the same-site /api/* proxy plays that role.
const dialogueFile = path.join(out, 'year-dialogue.js');
const dialogue = fs.readFileSync(dialogueFile, 'utf8');
const localOnly = "const served=/^https?:$/.test(root.location?.protocol||'')&&/^(127\\.0\\.0\\.1|localhost)$/.test(root.location?.hostname||'');";
const anyHost = "const served=/^https?:$/.test(root.location?.protocol||'');";
if (dialogue.split(localOnly).length !== 2) fail('the local-only AI check in year-dialogue.js changed; update build.cjs');
let webDialogue = dialogue.replace(localOnly, anyHost);

// Wording only: the settings panel speaks of a local launcher and key file, which web visitors do not have.
// If main rewords any of these, the build keeps going with the original text and says so.
const wording = [
  ["localStatus.error=String(v.error||'')", "localStatus.error=String(v.error||'');localStatus.errorEn=String(v.errorEn||v.error||'')"],
  ["(localStatus.error||'unknown reason')", "(localStatus.errorEn||localStatus.error||'unknown reason')"],
  ["w('本机没有找到 Key','No local key found')", "w('网站还没有配置 Key','This site has no key yet')"],
  ["w('把 deepseek-key.txt 放进 clementi-demo 文件夹，再重新运行“启动游戏.cmd”。','Put deepseek-key.txt in the clementi-demo folder, then run 启动游戏.cmd again.')", "w('可以先用离线对白。','Offline dialogue still works.')"],
  ['。启动窗口里也会显示原因。', '。'],
  ['. The launcher window shows the reason too.', '.'],
  ["w('本机服务没有回应','The local server did not answer')", "w('服务器没有回应','The server did not answer')"]
];
for (const [from, to] of wording) {
  if (webDialogue.split(from).length === 2) webDialogue = webDialogue.replace(from, to);
  else console.warn('note: settings wording not found, left as is: ' + from.slice(0, 60));
}
fs.writeFileSync(dialogueFile, webDialogue);

// 3. The proxy forwards only the game's own system prompts. Take them from this exact build.
const start = dialogue.indexOf('function systemPrompt(){');
const end = dialogue.indexOf('async function modelReply(', start);
if (start < 0 || end < 0) fail('systemPrompt() not found in year-dialogue.js');
const prompt = lang => new Function('language', dialogue.slice(start, end) + '\nreturn systemPrompt();')(() => lang);
const prompts = [prompt('zh'), prompt('en')];
if (prompts.some(p => typeof p !== 'string' || p.length < 200)) fail('systemPrompt() did not return the expected text');

// The host may bundle api/ before this script runs, so the prompt list is committed, not only generated.
// If it is stale on the host, stop: deployed pages and the proxy would disagree and every AI reply would fail.
const promptsFile = path.join(here, 'api', '_lib', 'prompts.mjs');
const promptsText = '// Generated by build.cjs from dist/year-dialogue.js systemPrompt(). Do not edit by hand.\nexport default ' + JSON.stringify(prompts, null, 2) + ';\n';
const previous = fs.existsSync(promptsFile) ? fs.readFileSync(promptsFile, 'utf8') : '';
if (previous !== promptsText) {
  if (process.env.VERCEL) fail('api/_lib/prompts.mjs is out of date. Run node clementi-demo/web/build.cjs locally and commit the file.');
  fs.writeFileSync(promptsFile, promptsText);
  console.log('updated api/_lib/prompts.mjs; commit it with this change');
}

const list = [];
(function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full); else list.push([path.relative(out, full).split(path.sep).join('/'), fs.statSync(full).size]);
  }
})(out);
const total = list.reduce((sum, [, size]) => sum + size, 0);
console.log('built ' + list.length + ' files, ' + (total / 1e6).toFixed(2) + ' MB in ' + path.relative(process.cwd(), out));
