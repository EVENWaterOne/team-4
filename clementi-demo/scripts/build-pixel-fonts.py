#!/usr/bin/env python3
"""Build dist/pixel-fonts.css: the pixel UI fonts, embedded so the offline single file works too.

Sources live in art-src/fonts/ (all SIL OFL 1.1, licence texts beside them):
  Jersey 10           display titles and big numbers (Latin)
  Silkscreen          small uppercase labels and tags (Latin)
  Be Vietnam Pro      body text (Latin)
  Fusion Pixel 12px   Chinese pixel glyphs for titles and labels

Fusion Pixel carries a Reserved Font Name, so the subset made here is renamed
"Downstairs Pixel SC". It keeps only the characters the game actually uses;
run this again after adding new Chinese text:

    pip install fonttools brotli
    python3 scripts/build-pixel-fonts.py
"""
import base64, io, pathlib, re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'art-src' / 'fonts'
DIST = ROOT / 'dist'
OUT = DIST / 'pixel-fonts.css'
PIXEL_FAMILY = 'Downstairs Pixel SC'

# Every character the default entry can show: scripts, page and stylesheets.
def used_characters():
    html = (DIST / 'index.html').read_text('utf-8')
    files = [DIST / 'index.html']
    files += [DIST / m for m in re.findall(r'<script defer src="([^"]+)"', html)]
    files += [DIST / m for m in re.findall(r'<link rel="stylesheet" href="([^"]+)"', html) if m != 'pixel-fonts.css']
    chars = set()
    for f in files:
        if f.name in ('scene.bundle.js', 'art-pack.js') or not f.exists():
            # scene.bundle.js is three.js plus a few Chinese map labels; read only its non-ASCII text.
            if f.name == 'scene.bundle.js' and f.exists():
                chars.update(c for c in f.read_text('utf-8', errors='ignore') if ord(c) > 0x2000)
            continue
        text = f.read_text('utf-8', errors='ignore')
        # \uXXXX escapes in scripts stand for real characters too.
        text += ''.join(chr(int(h, 16)) for h in re.findall(r'\\u([0-9a-fA-F]{4})', text))
        chars.update(text)
    chars.update(chr(c) for c in range(0x20, 0x7f))
    chars.update('，。、；：？！“”‘’（）《》【】—…·～￥％＋－×÷→←↑↓·「」『』〈〉')
    return ''.join(sorted(c for c in chars if ord(c) >= 0x20))

def pixel_subset(text):
    font = TTFont(SRC / 'FusionPixel-12px-Proportional-SC.woff2')
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(text=text)
    sub.subset(font)
    # A modified Fusion Pixel must not keep its reserved name.
    name = font['name']
    for rec in list(name.names):
        if rec.nameID in (1, 16):
            rec.string = PIXEL_FAMILY
        elif rec.nameID in (4,):
            rec.string = PIXEL_FAMILY + ' Regular'
        elif rec.nameID in (3,):
            rec.string = PIXEL_FAMILY.replace(' ', '') + '-subset'
        elif rec.nameID in (6,):
            rec.string = PIXEL_FAMILY.replace(' ', '') + '-Regular'
        elif rec.nameID == 5:
            rec.string = str(rec).strip() + '; subset for Downstairs'
    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf)
    return buf.getvalue()

def face(family, data, weight=400, style='normal'):
    b64 = base64.b64encode(data).decode('ascii')
    return ("@font-face{font-family:'%s';font-style:%s;font-weight:%d;font-display:swap;"
            "src:url(data:font/woff2;base64,%s) format('woff2')}" % (family, style, weight, b64))

def main():
    text = used_characters()
    pixel = pixel_subset(text)
    read = lambda n: (SRC / n).read_bytes()
    faces = [
        face('Jersey 10', read('Jersey10-Regular.latin.woff2')),
        face('Silkscreen', read('Silkscreen-Regular.latin.woff2')),
        face('Silkscreen', read('Silkscreen-Bold.latin.woff2'), 700),
        face('Be Vietnam Pro', read('BeVietnamPro-400.latin.woff2')),
        face('Be Vietnam Pro', read('BeVietnamPro-400italic.latin.woff2'), 400, 'italic'),
        face('Be Vietnam Pro', read('BeVietnamPro-500.latin.woff2'), 500),
        face('Be Vietnam Pro', read('BeVietnamPro-600.latin.woff2'), 600),
        face('Be Vietnam Pro', read('BeVietnamPro-700.latin.woff2'), 700),
        face(PIXEL_FAMILY, pixel),
    ]
    head = ('/* Generated by scripts/build-pixel-fonts.py. Do not edit by hand.\n'
            '   Jersey 10, Silkscreen, Be Vietnam Pro and Fusion Pixel 12px (subset, renamed "%s")\n'
            '   are licensed under the SIL Open Font License 1.1; see art-src/fonts/OFL-*.txt.\n'
            '   %d characters in the pixel subset. */\n' % (PIXEL_FAMILY, len(text)))
    OUT.write_text(head + '\n'.join(faces) + '\n', 'utf-8')
    print('%s  %d bytes  (pixel subset %d bytes, %d characters)' % (OUT, OUT.stat().st_size, len(pixel), len(text)))

if __name__ == '__main__':
    main()
